const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const {chromium} = require('playwright');
assert(process.env.PREVIEW_FILE, 'Set PREVIEW_FILE to the isolated preview metadata file');
const preview = JSON.parse(fs.readFileSync(process.env.PREVIEW_FILE, 'utf8'));
const token = fs.readFileSync(preview.tokenFile, 'utf8').trim();
const screenshot = (name) => path.join(__dirname, `${name}.png`);

(async () => {
  const browser = await chromium.launch({headless: true, executablePath: process.env.CHROMIUM_PATH});
  try {
    const context = await browser.newContext({viewport: {width: 1440, height: 1000}});
    const page = await context.newPage();
    const failures = [];
    page.on('pageerror', (error) => failures.push(error.message));
    page.on('console', (message) => { if (message.type() === 'error' && !message.text().includes('Failed to load resource')) failures.push(message.text()); });
    page.on('dialog', () => failures.push('Unexpected JavaScript dialog (possible XSS)'));
    const visible = async (selector) => page.locator(selector).waitFor({state: 'visible'});
    const loaded = async () => page.waitForFunction(() => document.querySelector('#results').getAttribute('aria-busy') === 'false');
    const login = async () => {
      await page.getByLabel('管理员令牌').fill(token);
      await page.getByRole('button', {name: '登录', exact: true}).click();
      await visible('#app-view'); await loaded();
    };
    const request = async (route, auth, method = 'GET', body, admin = false) => {
      const response = await fetch(`${preview.url}${route}`, {method, headers: {Authorization: `Bearer ${auth}`, ...(admin ? {'X-Admin-Request': '1'} : {}), ...(body ? {'Content-Type': 'application/json'} : {})}, body: body ? JSON.stringify(body) : undefined});
      assert(response.ok, `API ${route}: ${response.status}`);
      return response.status === 204 ? null : response.json();
    };

    await page.goto(`${preview.url}/admin/`);
    await page.screenshot({path: screenshot('login-desktop'), fullPage: true});
    await page.getByLabel('管理员令牌').fill('invalid-test-token');
    await page.getByRole('button', {name: '登录', exact: true}).click();
    await page.getByText('管理员令牌无效或已变更，请重新登录。').waitFor();
    await login();
    const username = `qa.alice.${Date.now().toString().slice(-6)}`.padEnd(64, 'x');
    await page.getByRole('button', {name: '创建用户', exact: true}).click();
    await page.getByLabel('用户名', {exact: true}).fill(username);
    await page.getByLabel('新密码', {exact: true}).fill('short');
    await page.getByLabel('确认密码').fill('short');
    await page.locator('#confirm-dialog').click();
    await page.getByText('密码长度须为 12 至 1024 字节。').waitFor();
    await page.getByLabel('新密码', {exact: true}).fill('preview test password');
    await page.getByLabel('确认密码').fill('does not match');
    await page.locator('#confirm-dialog').click();
    await page.getByText('两次输入的密码不一致。').waitFor();
    await page.getByLabel('确认密码').fill('preview test password');
    await page.locator('#confirm-dialog').click();
    await page.getByText('用户已创建。', {exact: true}).waitFor(); await loaded();
    await page.getByRole('button', {name: '创建用户', exact: true}).click();
    await page.getByLabel('用户名', {exact: true}).fill(username);
    await page.getByLabel('新密码', {exact: true}).fill('preview test password');
    await page.getByLabel('确认密码').fill('preview test password');
    await page.locator('#confirm-dialog').click();
    await page.getByText('用户名已存在。', {exact: true}).waitFor();
    await page.getByRole('button', {name: '取消', exact: true}).click();

    await page.getByRole('button', {name: `重置 ${username} 的密码`, exact: true}).click();
    await page.getByLabel('新密码', {exact: true}).fill('reset preview password');
    await page.getByLabel('确认密码').fill('reset preview password');
    await page.locator('#confirm-dialog').click();
    await page.getByText('密码已重置，已有登录与连接已失效。').waitFor(); await loaded();
    const users = await request('/v2/admin/users', token, 'GET', null, true);
    const user = users.items.find((item) => item.username === username);
    const device = async (name, platform) => request('/v2/auth/login', '', 'POST', {username, password: 'reset preview password', device_name: name, platform, public_key: crypto.randomBytes(32).toString('base64url')});
    const desktop = await device('开发工作站', 'desktop');
    const android = await device('Android QA', 'android');
    const ios = await device('<img src=x onerror=alert(1)>', 'ios');
    await request('/v2/devices/heartbeat', desktop.access_token, 'POST');
    await request('/v2/devices/heartbeat', android.access_token, 'POST');
    await request('/v2/devices/heartbeat', ios.access_token, 'POST');
    await request('/v2/connections', android.access_token, 'POST', {desktop_id: desktop.device_id});
    await page.getByRole('button', {name: '刷新', exact: true}).click(); await loaded();
    await page.screenshot({path: screenshot('users-desktop'), fullPage: true});
    await page.getByRole('button', {name: `查看 ${username} 的设备`, exact: true}).click(); await loaded();
    assert.equal(await page.getByLabel('按用户 ID 过滤').inputValue(), user.id);
    assert.equal(await page.locator('#table-body img').count(), 0);
    await page.getByText('<img src=x onerror=alert(1)>', {exact: true}).waitFor();
    await page.screenshot({path: screenshot('devices-desktop'), fullPage: true});
    await page.getByRole('button', {name: '撤销设备 Android QA', exact: true}).click();
    await page.screenshot({path: screenshot('revoke-confirmation'), fullPage: true});
    await page.locator('#confirm-dialog').click();
    await page.getByText('设备已撤销。', {exact: true}).waitFor(); await loaded();
    assert.equal((await fetch(`${preview.url}/v2/devices`, {headers: {Authorization: `Bearer ${android.access_token}`}})).status, 401);
    await request('/v2/devices/heartbeat', desktop.access_token, 'POST');
    await request('/v2/connections', ios.access_token, 'POST', {desktop_id: desktop.device_id});
    await page.getByRole('button', {name: '连接', exact: true}).click(); await loaded();
    await page.getByRole('button', {name: '撤销连接', exact: true}).filter({visible: true}).first().click();
    await page.locator('#confirm-dialog').click();
    await page.getByText('连接已撤销。', {exact: true}).waitFor(); await loaded();
    await page.screenshot({path: screenshot('connections-desktop'), fullPage: true});

    await page.getByRole('button', {name: '设备', exact: true}).click(); await loaded();
    await page.getByRole('searchbox', {name: '搜索', exact: true}).fill('no-such-device');
    await page.getByRole('button', {name: '搜索', exact: true}).click(); await loaded();
    await page.getByText('没有匹配的记录', {exact: true}).waitFor();
    await page.getByRole('button', {name: '清除筛选', exact: true}).click(); await loaded();
    await page.route('**/v2/admin/devices?**', (route) => route.fulfill({status: 503, body: ''}));
    await page.getByRole('button', {name: '刷新', exact: true}).click(); await loaded();
    await page.getByText('服务暂时不可用，请稍后刷新重试。').waitFor();
    await page.unroute('**/v2/admin/devices?**');
    await page.getByRole('button', {name: '刷新', exact: true}).click(); await loaded();
    await page.getByLabel('按用户 ID 过滤').fill(user.id);
    await page.getByRole('button', {name: '搜索', exact: true}).click(); await loaded();
    await page.setViewportSize({width: 320, height: 720});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '320px page overflow');
    await page.setViewportSize({width: 390, height: 844});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile page overflow');
    await page.screenshot({path: screenshot('devices-mobile'), fullPage: true});
    await page.getByRole('button', {name: '用户', exact: true}).click(); await loaded();
    await page.getByRole('button', {name: '创建用户', exact: true}).click();
    await page.screenshot({path: screenshot('create-mobile'), fullPage: true});
    await page.getByRole('button', {name: '取消', exact: true}).click();
    assert.deepEqual(await page.evaluate(() => ({local: localStorage.length, session: sessionStorage.length, cookie: document.cookie})), {local: 0, session: 0, cookie: ''});
    await page.getByRole('button', {name: '退出登录', exact: true}).click(); await visible('#login-view');
    assert.equal(await page.getByLabel('管理员令牌').inputValue(), '');
    await page.screenshot({path: screenshot('login-mobile'), fullPage: true});
    await login(); await page.reload(); await visible('#login-view');
    assert.deepEqual(failures, []);
    const report = {browser: await browser.version(), desktop: '1440x1000', mobile: '390x844 and 320x720', checks: ['login rejection and success', 'create validation and persistence', 'duplicate username', 'password reset', 'user filter', 'XSS literal rendering', 'device revocation and access denial', 'connection revocation', 'search empty state', 'server error and retry', 'mobile overflow', 'no browser storage', 'logout and reload clear token'], consoleErrors: failures};
    fs.writeFileSync(path.join(__dirname, 'browser-verification.json'), JSON.stringify(report, null, 2) + '\n');
    console.log(JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
